/** Look a string up; fall back to Indonesian, then the key itself. */
export function t(key, lang = 'id') {
  const table = STRINGS[lang] || STRINGS.id;
  return table[key] ?? STRINGS.id[key] ?? key;
}

/** Mission + dialog text lives with the content that owns it, but every
 *  line is a {id, en} pair so the game can flip language mid-session. */
export function pickText(pair, lang = 'id') {
  if (!pair) return '';
  if (typeof pair === 'string') return pair;
  return pair[lang] || pair.en || pair.id || '';
}
