export class Lang {
  constructor(code = 'id') {
    this.code = LANGS.includes(code) ? code : 'id';
  }

  set(code) {
    if (LANGS.includes(code)) this.code = code;
  }

  t(key) {
    const table = STRINGS[this.code] || STRINGS.id;
    if (key in table) return table[key];
    if (key in STRINGS.id) return STRINGS.id[key];
    return key;
  }
}

